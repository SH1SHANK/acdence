export function getCanonicalEvents(): AcademicEvent[] {
  return [...CANONICAL_EVENTS];
}

export function getEventById(id: string): AcademicEvent | undefined {
  return CANONICAL_EVENTS.find((e) => e.id === id);
}

export function getHardCutoffs(): AcademicEvent[] {
  return CANONICAL_EVENTS.filter((e) => e.hardCutoff || e.isHardCutoff);
}

export function getEventsForCourse(courseCode: CourseCode): AcademicEvent[] {
  return CANONICAL_EVENTS.filter((e) => !e.courseCode || e.courseCode === courseCode);
}
